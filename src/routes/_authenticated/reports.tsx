import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { FileBarChart, FileText, UsersRound, HandCoins, ShieldAlert, ScrollText, Download } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";
import { AppShell, PageHeader } from "@/components/app-shell";
import { formatDateTime } from "@/lib/format";

export const Route = createFileRoute("/_authenticated/reports")({
  head: () => ({
    meta: [
      { title: "Reports — OSUSUGUARD AI" },
      { name: "description", content: "Generate member, group, fraud, contribution, and audit reports." },
    ],
  }),
  component: ReportsPage,
});

const reportTypes = [
  { type: "member", icon: FileText, title: "Member Report", desc: "Individual contribution history, risk profile, and fraud record." },
  { type: "group", icon: UsersRound, title: "Group Report", desc: "Group performance, cycle status, and member breakdown." },
  { type: "fraud", icon: ShieldAlert, title: "Fraud Report", desc: "All alerts with explanations, risk scores, and resolutions." },
  { type: "contribution", icon: HandCoins, title: "Contribution Report", desc: "Full transaction ledger across all sources." },
  { type: "audit", icon: ScrollText, title: "Audit Report", desc: "Complete audit trail of user and system actions." },
];

function ReportsPage() {
  const queryClient = useQueryClient();
  const [generating, setGenerating] = useState<string | null>(null);

  const { data: reports } = useQuery({
    queryKey: ["reports"],
    queryFn: async () => (await supabase.from("reports").select("*").order("created_at", { ascending: false })).data ?? [],
  });

  async function generate(type: string, title: string) {
    setGenerating(type);
    const { error } = await supabase.from("reports").insert({
      title: `${title} — ${new Date().toLocaleDateString("en-GB", { month: "long", year: "numeric" })}`,
      report_type: type,
      generated_by: "You",
    });
    setGenerating(null);
    if (error) {
      toast.error("Could not generate report", { description: error.message });
      return;
    }
    await supabase.from("audit_logs").insert({
      actor_name: "You", action: "generated_report", entity_type: "report", entity_ref: title, details: "Report generated from reporting module",
    });
    toast.success("Report generated", { description: "Your report is ready in the list below." });
    queryClient.invalidateQueries({ queryKey: ["reports"] });
  }

  return (
    <AppShell>
      <PageHeader title="Reporting Module" subtitle="Generate professional reports for groups, members, and auditors" />

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-3">
        {reportTypes.map(({ type, icon: Icon, title, desc }) => (
          <div key={type} className="glass glass-hover rounded-2xl p-6 animate-fade-up">
            <div className="mb-3 flex h-11 w-11 items-center justify-center rounded-xl bg-gold/15">
              <Icon className="h-5 w-5 text-gold" />
            </div>
            <h3 className="font-display text-base font-semibold">{title}</h3>
            <p className="mt-1 text-xs leading-relaxed text-muted-foreground">{desc}</p>
            <button
              onClick={() => generate(type, title)}
              disabled={generating === type}
              className="mt-4 flex items-center gap-2 rounded-xl bg-primary px-4 py-2 text-xs font-semibold text-primary-foreground transition-all hover:brightness-110 disabled:opacity-60"
            >
              <Download className="h-3.5 w-3.5" />
              {generating === type ? "Generating…" : "Generate report"}
            </button>
          </div>
        ))}
      </div>

      <div className="glass mt-8 overflow-hidden rounded-2xl animate-fade-up">
        <div className="border-b border-border px-6 py-4">
          <h3 className="flex items-center gap-2 font-display text-lg font-semibold">
            <FileBarChart className="h-5 w-5 text-primary" /> Generated Reports
          </h3>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-border text-left text-xs uppercase tracking-wider text-muted-foreground">
                <th className="px-6 py-4">Title</th>
                <th className="px-6 py-4">Type</th>
                <th className="px-6 py-4">Generated by</th>
                <th className="px-6 py-4">Date</th>
              </tr>
            </thead>
            <tbody>
              {reports?.map((r) => (
                <tr key={r.id} className="border-b border-border/50 transition-colors hover:bg-secondary/30">
                  <td className="px-6 py-4 font-medium">{r.title}</td>
                  <td className="px-6 py-4">
                    <span className="rounded-full bg-primary/15 px-2.5 py-0.5 text-[10px] font-semibold uppercase text-primary">
                      {r.report_type}
                    </span>
                  </td>
                  <td className="px-6 py-4 text-muted-foreground">{r.generated_by ?? "—"}</td>
                  <td className="px-6 py-4 text-muted-foreground">{formatDateTime(r.created_at)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </AppShell>
  );
}
